export const DICTIONARIES: Record<Lang, Record<string, string>> = { tr, en };

let current: Lang = 'tr';

export function setLang(lang: Lang): void {
  current = lang;
  if (typeof document !== 'undefined') document.documentElement.lang = lang;
}

export function getLang(): Lang {
  return current;
}

export function detectLang(): Lang {
  const lang = typeof navigator !== 'undefined' ? navigator.language : '';
  return typeof lang === 'string' && lang.toLowerCase().startsWith('en') ? 'en' : 'tr';
}

/** Anahtar yoksa anahtarın kendisini döner; {ad} biçimindeki yer tutucuları doldurur. */
export function t(key: string, params: Record<string, string> = {}): string {
  const text = DICTIONARIES[current][key] ?? key;
  return text.replace(/\{(\w+)\}/g, (whole, name: string) => params[name] ?? whole);
}
